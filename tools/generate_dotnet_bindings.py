"""Generate raw C# ABI declarations from the public C header (no third-party deps)."""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
header = (root / 'native/videolab_core/include/videolab_core.h').read_text(encoding='utf-8')
source = re.sub(r'/\*.*?\*/', '', header, flags=re.S)
types = {'uint32_t': 'uint', 'uint64_t': 'ulong', 'int32_t': 'int',
         'int64_t': 'long', 'uint8_t': 'byte', 'double': 'double', 'void': 'void'}
enums = set(re.findall(r'typedef enum (\w+)', source))
structs = set(re.findall(r'typedef struct (\w+)\s*\{', source))

def scalar(value):
    value = value.strip().replace('const ', '')
    if '*' in value or value.endswith('Fn'):
        return 'nint'
    if value in enums:
        return 'int'
    return types.get(value, value)

lines = ['// Generated by tools/generate_dotnet_bindings.py from videolab_core.h.',
         '#nullable enable',
         'using System.Runtime.InteropServices;', 'namespace VideoLab.Interop;', '']
for name, fields in re.findall(r'typedef struct (\w+)\s*\{(.*?)\}\s*\w+;', source, re.S):
    lines += ['[StructLayout(LayoutKind.Sequential)]', f'public unsafe struct {name}', '{']
    for field in fields.split(';'):
        field = field.strip()
        if not field:
            continue
        match = re.fullmatch(r'(.+?)(\w+)\s*(?:\[(\d+)\])?', field, re.S)
        if not match:
            raise ValueError(field)
        kind, variable, count = match.groups()
        declaration = f'fixed {scalar(kind)} {variable}[{count}]' if count else f'{scalar(kind)} {variable}'
        lines.append(f'    public {declaration};')
    lines += ['}', '']
lines += ['public static class Native', '{', '    public const string Library = "videolab_core";']
for result, name, arguments in re.findall(r'VD_CORE_API\s+([\w\s*]+?)\s+(vd_\w+)\s*\((.*?)\);', source, re.S):
    params = []
    for arg in arguments.split(','):
        arg = ' '.join(arg.split())
        if arg == 'void':
            continue
        match = re.fullmatch(r'(.+?)(\w+)', arg)
        kind, variable = match.groups()
        base = kind.replace('const ', '').replace('*', '').strip()
        if base in structs and '*' in kind:
            mapped = f'ref {base}'
        elif base in ('uint8_t', 'uint32_t', 'uint64_t', 'int32_t', 'int64_t', 'double') and '*' in kind:
            mapped = f'out {scalar(base)}'
        elif kind.count('*') == 2:
            mapped = 'out nint'
        elif base == 'char' and '*' in kind and name != 'vd_string_free':
            mapped = '[MarshalAs(UnmanagedType.LPUTF8Str)] string?'
        else:
            mapped = scalar(kind)
        params.append(f'{mapped} @{variable}')
    lines += ['    [DllImport(Library, CallingConvention = CallingConvention.Cdecl)]',
              f'    public static extern {scalar(result)} {name}({", ".join(params)});']
lines += ['}', '']
target = root / 'src/VideoLab.Interop/Native.g.cs'
target.write_text('\n'.join(lines), encoding='utf-8')
print(f'{len(structs)} structs and {sum("extern " in line for line in lines)} functions generated')
